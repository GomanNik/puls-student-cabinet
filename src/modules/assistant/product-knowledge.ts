export function answerProductQuestion(message: string, history: AssistantTurn[] = []): ProductHelpResult | null {
  const topic = classifyProductHelp(message, history);
  if (!topic) return null;
  return {
    topic,
    answer: {
      text: answerFor(topic),
      providerMode: "DEMO_MOCK",
      completeness: "COMPLETE",
      targets: [],
      notice,
    },
  };
}
