import type { AssistantAnswer } from "@/shared/contracts/student-api";
import type { AssistantTurn } from "@/server/integrations/assistant-provider";

/**
 * Короткие проверенные ответы о продукте. Сверены с 02–04, 06–08 и реальной
 * студенческой навигацией. При изменении состава разделов обновлять вместе
 * с пользовательскими сценариями; не добавлять сюда не реализованные функции.
 */

export type ProductHelpTopic =
  | "OVERVIEW"
  | "FEATURES"
  | "START"
  | "LOGIN"
  | "SCHEDULE"
  | "TEACHERS"
  | "STUDY"
  | "GRADES"
  | "WORKS"
  | "MATERIALS"
  | "REQUESTS"
  | "APPEALS"
  | "CALENDAR"
  | "NOTIFICATIONS"
  | "PROFILE"
  | "ASSISTANT"
  | "READ_ONLY"
  | "ROLES"
  | "INTEGRATIONS";

export type ProductHelpResult = {
  answer: AssistantAnswer;
  topic: ProductHelpTopic;
};

const notice = "База знаний ПУЛЬС: ответ основан на подтверждённой структуре конкурсного прототипа.";
const normalize = (value: string) => value.toLocaleLowerCase("ru-RU").replaceAll("ё", "е").replace(/[«»„“"'`]/gu, " ").replace(/\s+/gu, " ").trim();

const whereIntent = /(?:где\s+(?:посмотреть|найти|открыть|искать|находится|кнопка|вкладка|экспорт|раздел|меню)|в\s+каком\s+разделе|в\s+каком\s+месте|куда\s+(?:перейти|нажать))/u;
const howIntent = /(?:как\s+(?:пользоваться|посмотреть|найти|открыть|перейти|экспортировать|скачать|просмотреть|прочитать|войти|создать|получить|подать|написать|ответить|отправить|проверить|узнать|работает)|с\s+чего\s+начать|как\s+начать|первый\s+раз|инструкц)/u;
const capabilityIntent = /(?:можно\s+ли|есть\s+ли\s+возможность|поддерживает\s+ли|что\s+такое|что\s+умеет|какие\s+(?:функции|разделы|возможности)|что\s+входит\s+в|предусмотрен\s+ли)/u;
const helpIntent = (value: string) => whereIntent.test(value) || howIntent.test(value) || capabilityIntent.test(value);
const assistantTerm = /(?:^|[^а-яё])(?:помощник[а-яё]*|ии[- ]?помощник[а-яё]*|чат)(?=$|[^а-яё])/u;

function topicForDirectQuestion(message: string): ProductHelpTopic | null {
  const q = normalize(message);
  const productAnchor = /пульс|кабинет|интерфейс|навигац|раздел|меню/u.test(q);
  const mentionsProduct = productAnchor || /функци|возможност/u.test(q);
  const navigationIntent = whereIntent.test(q) || howIntent.test(q) || /(?:можно\s+ли|есть\s+ли\s+возможность)\s+(?:смотреть|посмотреть|найти|открыть|перейти)/u.test(q);
  const help = helpIntent(q) || (productAnchor && /расскажи|объясни|опиши|покажи/u.test(q));

  if (/что\s+(?:такое|представляет\s+собой)\s+(?:проект\s+)?пульс|пульс\s*[-—:]?\s*(?:что\s+это|это\s+что)|что\s+за\s+проект\s+пульс|расскажи\s+(?:мне\s+)?о\s+пульс|что\s+такое\s+(?:личн(?:ый|ого|ом)\s+)?кабинет(?:\s+студента)?|как\s+(?:устроен|работает)\s+(?:пульс|личн(?:ый|ого|ом)\s+кабинет)/u.test(q)) return "OVERVIEW";
  if (assistantTerm.test(q) && /(?:какие\s+функции|что\s+умеет|как\s+пользоваться|что\s+может)/u.test(q)) return "ASSISTANT";
  if (productAnchor && /(?:какие\s+(?:функции|разделы|возможности)|что\s+умеет|что\s+входит\s+в|возможности)/u.test(q)) return "FEATURES";
  if (productAnchor && /(?:как\s+пользоваться|с\s+чего\s+начать|как\s+начать\s+работу|первый\s+раз)/u.test(q)) return "START";

  if (/(?:кабинет|интерфейс)\s+(?:преподавател|сотрудник|деканат|администратор)|(?:преподавател|сотрудник|деканат|администратор).{0,35}(?:свой\s+)?кабинет|кабинет.{0,35}(?:преподавател|сотрудник|деканат|администратор)/u.test(q)) return "ROLES";
  if (/(?:реальн|настоящ|действующ).{0,35}(?:вуз|университет|систем|данн|подключен)|(?:вуз|университет).{0,35}(?:подключен|интеграц)|подключен[аоы]?.{0,35}(?:реальн|университет|вуз)|интеграц.{0,35}(?:вуз|университет)|реальные\s+данные|использует\s+ли.{0,35}(?:реальные|настоящие)\s+данные|есть\s+ли.{0,25}(?:подключение|интеграция).{0,25}(?:вуз|университет)|подключен\s+ли.{0,25}(?:к\s+)?(?:вузу|университету)|подключение.{0,30}(?:к\s+)?(?:вузу|университету)|интеграция\s+с\s+(?:вузом|университетом)/u.test(q)) return "INTEGRATIONS";
  if (/(?:измен|поменя|меня|исправ|редакт|выстав|постав|смен|выбрать|отмет|простав|запис|перевест).{0,45}(?:оценк|посещ|подгрупп|расписан|преподавател)|(?:сда(?:ть|вать)|загруз|отправ|прикрепить).{0,45}(?:работ|задан)|(?:работ|задан).{0,45}(?:загруз|отправ|сда(?:ть|вать))/u.test(q)) return "READ_ONLY";

  if (/(?:войти|авторизац|логин|парол)/u.test(q) && (help || mentionsProduct || /как\s+войти/u.test(q))) return "LOGIN";
  if (assistantTerm.test(q) && (help || mentionsProduct)) return "ASSISTANT";

  // Запросы «где/как посмотреть» относятся к навигации по интерфейсу.
  // Вопросы о фактическом содержимом («что завтра», «кто ведёт») остаются академическими.
  if (!navigationIntent) return null;
  if (/преподавател|учител/u.test(q)) return "TEACHERS";
  if (/расписан|заняти|парах|пары/u.test(q)) return "SCHEDULE";
  if (/оценк|успеваем|балл|экзамен|зачет|аттест|результат/u.test(q)) return "GRADES";
  if (/посещаем|посещени|дисциплин|предмет|семестр|учебн.{0,12}деятельност/u.test(q)) return "STUDY";
  if (/работ|задан|срок|дедлайн|курсов/u.test(q)) return "WORKS";
  if (/материал|файл|методич|конспект|презентац|лекци/u.test(q)) return "MATERIALS";
  if (/заявк|справк|заявлен/u.test(q)) return "REQUESTS";
  if (/обращен|переписк|ответ.{0,20}деканат/u.test(q)) return "APPEALS";
  if (/календар|экспорт|ics|pdf|xlsx|событи/u.test(q)) return "CALENDAR";
  if (/уведомлен|объявлен/u.test(q)) return "NOTIFICATIONS";
  if (/профил|личн.{0,10}данн/u.test(q)) return "PROFILE";

  if (productAnchor && /что\s+(?:такое|это)|описан|назначен/u.test(q)) return "OVERVIEW";
  if (productAnchor && /функци|возможност|раздел|умеет|интерфейс/u.test(q)) return "FEATURES";
  return null;
}

export function classifyProductHelp(message: string, history: AssistantTurn[] = []): ProductHelpTopic | null {
  const direct = topicForDirectQuestion(message);
  if (direct) return direct;

  const q = normalize(message);
  const shortFollowUp = /^(?:а\s+)?(?:как|где|куда)\s+(?:туда|там|это|в\s+него|в\s+нее|в\s+неё|к\s+нему|к\s+ней)|^(?:а\s+)?(?:дальше|что\s+теперь)\s*\??$/u.test(q);
  if (!shortFollowUp) return null;

  const previousQuestion = history.at(-2)?.content;
  return previousQuestion ? topicForDirectQuestion(previousQuestion) : null;
}

